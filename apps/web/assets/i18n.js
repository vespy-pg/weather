let activeLanguage = 'en';

export function t(key, replacements = {}) {
  const template = MESSAGES[activeLanguage]?.[key] ?? MESSAGES.en[key] ?? key;
  return Object.entries(replacements).reduce((value, [name, replacement]) => value.replaceAll(`{${name}}`, replacement), template);
}

export function setLanguage(language) {
  activeLanguage = language === 'pl' ? 'pl' : 'en';
  document.documentElement.lang = activeLanguage;
  document.querySelectorAll('[data-i18n]').forEach(element => { element.textContent = t(element.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(element => { element.placeholder = t(element.dataset.i18nPlaceholder); });
  return activeLanguage;
}

export function language() {
  return activeLanguage;
}

export function locale() {
  return activeLanguage === 'pl' ? 'pl-PL' : 'en-GB';
}
